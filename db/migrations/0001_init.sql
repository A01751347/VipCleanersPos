CREATE VIEW vw_ordenes_detalle AS
SELECT
  o.orden_id, o.codigo_orden, o.codigo_seguimiento, o.origen,
  o.cliente_id,
  c.nombre AS cliente_nombre, c.apellidos AS cliente_apellidos,
  c.telefono AS cliente_telefono, c.email AS cliente_email,
  o.empleado_recepcion_id, o.empleado_entrega_id,
  NULLIF(TRIM(CONCAT_WS(' ', er.nombre, er.apellidos)), '') AS empleado_recepcion,
  NULLIF(TRIM(CONCAT_WS(' ', ee.nombre, ee.apellidos)), '') AS empleado_entrega,
  o.estado_actual_id,
  es.nombre AS estado_servicio, es.color AS color_estado, es.orden AS estado_orden,
  es.es_final AS estado_es_final,
  o.subtotal, o.descuento, o.impuestos, o.total,
  o.estado_pago, o.metodo_pago,
  COALESCE(pg.total_pagado, 0)                 AS total_pagado,
  o.total - COALESCE(pg.total_pagado, 0)       AS saldo_pendiente,
  o.requiere_identificacion, o.tiene_identificacion_registrada,
  o.requiere_pickup, o.costo_pickup, o.zona_pickup, o.direccion_id,
  o.fecha_reservacion, o.fecha_recepcion, o.fecha_entrega_estimada, o.fecha_entrega_real,
  o.cancelada, o.cancelada_en, o.motivo_cancelacion,
  o.acepta_terminos, o.acepta_whatsapp, o.consent_at,
  o.notas, o.fecha_creacion, o.fecha_actualizacion,
  (SELECT COUNT(*) FROM detalles_orden_servicios d WHERE d.orden_id = o.orden_id) AS total_pares
FROM ordenes o
JOIN clientes c          ON c.cliente_id = o.cliente_id
LEFT JOIN empleados er   ON er.empleado_id = o.empleado_recepcion_id
LEFT JOIN empleados ee   ON ee.empleado_id = o.empleado_entrega_id
JOIN estados_servicio es ON es.estado_id = o.estado_actual_id
LEFT JOIN (
  SELECT orden_id, SUM(monto) AS total_pagado
  FROM pagos WHERE estado = 'completado'
  GROUP BY orden_id
) pg ON pg.orden_id = o.orden_id;

CREATE VIEW vw_detalles_orden_servicios AS
SELECT
  d.detalle_servicio_id, d.orden_id, d.servicio_id,
  s.nombre AS servicio_nombre, s.descripcion AS servicio_descripcion,
  s.tiempo_estimado_minutos,
  d.cantidad, d.precio_unitario, d.descuento, d.subtotal,
  d.modelo_id, d.marca, d.modelo, d.talla, d.color, d.descripcion_calzado,
  d.caja_almacenamiento, d.codigo_ubicacion, d.notas_especiales,
  m.nombre AS modelo_catalogo, mk.nombre AS marca_catalogo,
  (SELECT COUNT(*) FROM archivos_media a
    WHERE a.detalle_servicio_id = d.detalle_servicio_id
      AND a.tipo IN ('calzado_entrada','calzado_salida')) AS total_fotos,
  d.fecha_creacion
FROM detalles_orden_servicios d
JOIN servicios s            ON s.servicio_id = d.servicio_id
LEFT JOIN modelos_calzado m ON m.modelo_id = d.modelo_id
LEFT JOIN marcas mk         ON mk.marca_id = m.marca_id;

CREATE VIEW vw_detalles_orden_productos AS
SELECT
  d.detalle_producto_id, d.orden_id, d.producto_id,
  p.nombre AS producto_nombre, p.descripcion AS producto_descripcion,
  p.codigo_barras, cat.nombre AS categoria,
  d.cantidad, d.precio_unitario, d.descuento, d.subtotal, d.fecha_creacion
FROM detalles_orden_productos d
JOIN productos p            ON p.producto_id = d.producto_id
JOIN categorias_productos cat ON cat.categoria_id = p.categoria_id;

CREATE VIEW vw_historial_estados AS
SELECT
  h.historial_id, h.orden_id, h.estado_id,
  e.nombre AS estado_nombre, e.color AS estado_color, e.orden AS estado_orden,
  h.empleado_id,
  NULLIF(TRIM(CONCAT_WS(' ', emp.nombre, emp.apellidos)), '') AS empleado_nombre,
  h.comentario, h.fecha_cambio
FROM historial_estados h
JOIN estados_servicio e ON e.estado_id = h.estado_id
LEFT JOIN empleados emp ON emp.empleado_id = h.empleado_id;

CREATE VIEW vw_inventario_actual AS
SELECT
  p.producto_id, p.nombre AS producto_nombre, p.nombre, p.descripcion,
  p.categoria_id, cat.nombre AS categoria,
  p.precio, p.costo, p.stock, p.stock_minimo, p.codigo_barras, p.activo,
  (p.stock * p.costo)  AS valor_inventario,
  (p.stock <= p.stock_minimo) AS stock_bajo,
  (p.stock = 0)        AS agotado
FROM productos p
JOIN categorias_productos cat ON cat.categoria_id = p.categoria_id;

CREATE VIEW vw_movimientos_inventario AS
SELECT
  m.movimiento_id, m.producto_id, p.nombre AS producto_nombre, p.codigo_barras,
  m.tipo_movimiento, m.cantidad, m.stock_anterior, m.stock_nuevo,
  m.orden_id, o.codigo_orden,
  m.empleado_id,
  NULLIF(TRIM(CONCAT_WS(' ', e.nombre, e.apellidos)), '') AS empleado_nombre,
  m.motivo, m.fecha_movimiento
FROM inventario_movimientos m
JOIN productos p     ON p.producto_id = m.producto_id
LEFT JOIN ordenes o  ON o.orden_id = m.orden_id
LEFT JOIN empleados e ON e.empleado_id = m.empleado_id;

CREATE VIEW vw_mapa_ubicaciones AS
SELECT
  d.caja_almacenamiento, d.codigo_ubicacion, d.detalle_servicio_id,
  d.orden_id, o.codigo_orden, o.fecha_recepcion, o.fecha_entrega_estimada,
  d.marca, d.modelo, d.talla, d.color, d.descripcion_calzado, d.notas_especiales,
  s.nombre AS servicio_nombre,
  NULLIF(TRIM(CONCAT_WS(' ', c.nombre, c.apellidos)), '') AS cliente,
  c.telefono AS cliente_telefono,
  es.nombre AS estado_orden, es.color AS estado_color,
  (o.fecha_entrega_estimada < now() AND NOT es.es_final) AS retrasada
FROM detalles_orden_servicios d
JOIN ordenes o           ON o.orden_id = d.orden_id
JOIN clientes c          ON c.cliente_id = o.cliente_id
JOIN servicios s         ON s.servicio_id = d.servicio_id
JOIN estados_servicio es ON es.estado_id = o.estado_actual_id
WHERE d.codigo_ubicacion IS NOT NULL AND NOT o.cancelada;

