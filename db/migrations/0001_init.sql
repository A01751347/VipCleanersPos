CREATE VIEW vw_servicios_populares AS
SELECT
  s.servicio_id, s.nombre, s.precio,
  COUNT(d.detalle_servicio_id) AS total_vendidos,
  COALESCE(SUM(d.subtotal), 0) AS ingresos
FROM servicios s
LEFT JOIN detalles_orden_servicios d ON d.servicio_id = s.servicio_id
LEFT JOIN ordenes o ON o.orden_id = d.orden_id AND NOT o.cancelada
GROUP BY s.servicio_id, s.nombre, s.precio
ORDER BY total_vendidos DESC;

CREATE VIEW vw_productos_populares AS
SELECT
  p.producto_id, p.nombre, p.precio,
  COALESCE(SUM(d.cantidad), 0) AS total_vendidos,
  COALESCE(SUM(d.subtotal), 0) AS ingresos
FROM productos p
LEFT JOIN detalles_orden_productos d ON d.producto_id = p.producto_id
LEFT JOIN ordenes o ON o.orden_id = d.orden_id AND NOT o.cancelada
GROUP BY p.producto_id, p.nombre, p.precio
ORDER BY total_vendidos DESC;

CREATE VIEW vw_estadisticas_ventas_mensuales AS
SELECT
  date_trunc('month', o.fecha_recepcion)::date AS mes,
  to_char(o.fecha_recepcion, 'YYYY-MM')        AS periodo,
  COUNT(*)                                      AS total_ordenes,
  COALESCE(SUM(o.subtotal), 0)                  AS subtotal,
  COALESCE(SUM(o.impuestos), 0)                 AS impuestos,
  COALESCE(SUM(o.total), 0)                     AS total,
  COALESCE(AVG(o.total), 0)                     AS ticket_promedio
FROM ordenes o
WHERE NOT o.cancelada
GROUP BY 1, 2
ORDER BY 1 DESC;

CREATE VIEW vw_reporte_empleados AS
SELECT
  e.empleado_id,
  NULLIF(TRIM(CONCAT_WS(' ', e.nombre, e.apellidos)), '') AS empleado_nombre,
  e.puesto, e.activo,
  COALESCE(ord.ordenes_recibidas, 0) AS ordenes_recibidas,
  COALESCE(ord.total_vendido, 0)     AS total_vendido,
  COALESCE(pay.pagos_registrados, 0) AS pagos_registrados,
  COALESCE(pay.monto_cobrado, 0)     AS monto_cobrado
FROM empleados e
LEFT JOIN (
  SELECT empleado_recepcion_id AS empleado_id,
         COUNT(*) AS ordenes_recibidas,
         SUM(total) AS total_vendido
  FROM ordenes WHERE NOT cancelada
  GROUP BY empleado_recepcion_id
) ord ON ord.empleado_id = e.empleado_id
LEFT JOIN (
  SELECT empleado_id,
         COUNT(*) AS pagos_registrados,
         SUM(monto) AS monto_cobrado
  FROM pagos WHERE estado = 'completado'
  GROUP BY empleado_id
) pay ON pay.empleado_id = e.empleado_id;

