-- ---------- Trigger genérico de fecha_actualizacion --------------------------
CREATE OR REPLACE FUNCTION set_fecha_actualizacion()
RETURNS TRIGGER AS $fn$
BEGIN
  NEW.fecha_actualizacion = now();
  RETURN NEW;
END;
$fn$ LANGUAGE plpgsql;

