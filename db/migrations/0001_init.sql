CREATE TABLE pagos (
  pago_id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_id          INT NOT NULL REFERENCES ordenes(orden_id) ON DELETE CASCADE,
  -- monto = lo que se aplica a la orden. NUNCA el billete recibido (DAT-06).
  monto             NUMERIC(10,2) NOT NULL CHECK (monto <> 0),
  efectivo_recibido NUMERIC(10,2) NULL CHECK (efectivo_recibido >= 0),
  cambio_entregado  NUMERIC(10,2) NULL CHECK (cambio_entregado >= 0),
  metodo            metodo_pago NOT NULL,
  referencia        VARCHAR(120) NULL,
  terminal_id       VARCHAR(60)  NULL,
  empleado_id       INT NOT NULL REFERENCES empleados(empleado_id),
  corte_id          INT NULL REFERENCES cortes_caja(corte_id),
  estado            estado_pago NOT NULL DEFAULT 'completado',
  -- Un reembolso es un pago negativo que apunta al pago original (OPS-03)
  pago_original_id  INT NULL REFERENCES pagos(pago_id),
  motivo            TEXT NULL,
  fecha_pago        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_pago_orden   ON pagos (orden_id);
CREATE INDEX idx_pago_fecha   ON pagos (fecha_pago DESC);
CREATE INDEX idx_pago_corte   ON pagos (corte_id) WHERE corte_id IS NOT NULL;
CREATE INDEX idx_pago_empleado ON pagos (empleado_id, fecha_pago DESC);

