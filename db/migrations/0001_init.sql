CREATE TABLE cortes_caja (
  corte_id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empleado_id         INT NOT NULL REFERENCES empleados(empleado_id),
  estado              estado_corte NOT NULL DEFAULT 'abierto',
  fondo_inicial       NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (fondo_inicial >= 0),
  abierto_en          TIMESTAMPTZ NOT NULL DEFAULT now(),
