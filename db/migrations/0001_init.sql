-- =============================================================================
-- Órdenes
-- Una "reserva en línea" es una orden con origen='online'. No hay tabla
-- reservaciones separada: ese modelo paralelo causaba que las reservas nunca
-- aparecieran en el panel (FUN-03).
-- =============================================================================
CREATE TABLE ordenes (
  orden_id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_orden            VARCHAR(24) NOT NULL UNIQUE,
  -- Token de alta entropía para el seguimiento público. El codigo_orden es
  -- corto y legible para el mostrador; este es el que no se puede adivinar.
  codigo_seguimiento      VARCHAR(64) NOT NULL UNIQUE,
  origen                  origen_orden NOT NULL DEFAULT 'pos',

  cliente_id              INT NOT NULL REFERENCES clientes(cliente_id),
  empleado_recepcion_id   INT NULL REFERENCES empleados(empleado_id),
  empleado_entrega_id     INT NULL REFERENCES empleados(empleado_id),
  direccion_id            INT NULL REFERENCES direcciones(direccion_id) ON DELETE SET NULL,

  -- Importes: se calculan SIEMPRE en el servidor (SEC-04).
  subtotal                NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
  descuento               NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (descuento >= 0),
  impuestos               NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (impuestos >= 0),
  total                   NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
  motivo_descuento        VARCHAR(200) NULL,
  descuento_autorizado_por INT NULL REFERENCES empleados(empleado_id),

  estado_actual_id        INT NOT NULL REFERENCES estados_servicio(estado_id),
  estado_pago             estado_pago_orden NOT NULL DEFAULT 'pendiente',
  metodo_pago             metodo_pago NULL,

  requiere_identificacion BOOLEAN NOT NULL DEFAULT FALSE,
  tiene_identificacion_registrada BOOLEAN NOT NULL DEFAULT FALSE,

  -- Recolección a domicilio
  requiere_pickup         BOOLEAN NOT NULL DEFAULT FALSE,
  costo_pickup            NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (costo_pickup >= 0),
  zona_pickup             VARCHAR(80) NULL,

  fecha_reservacion       TIMESTAMPTZ NULL,   -- franja solicitada (online)
  fecha_recepcion         TIMESTAMPTZ NOT NULL DEFAULT now(),
  fecha_entrega_estimada  TIMESTAMPTZ NOT NULL,
  fecha_entrega_real      TIMESTAMPTZ NULL,

  -- Cancelación (OPS-03)
  cancelada               BOOLEAN NOT NULL DEFAULT FALSE,
  cancelada_en            TIMESTAMPTZ NULL,
  cancelada_por           INT NULL REFERENCES empleados(empleado_id),
  motivo_cancelacion      TEXT NULL,

  -- Consentimiento
  acepta_terminos         BOOLEAN NOT NULL DEFAULT FALSE,
  acepta_whatsapp         BOOLEAN NOT NULL DEFAULT FALSE,
  consent_at              TIMESTAMPTZ NULL,

  notas                   TEXT NULL,
  fecha_creacion          TIMESTAMPTZ NOT NULL DEFAULT now(),
  fecha_actualizacion     TIMESTAMPTZ NOT NULL DEFAULT now(),

  CHECK (total >= 0),
  CHECK (NOT cancelada OR cancelada_en IS NOT NULL)
);
CREATE INDEX idx_orden_cliente        ON ordenes (cliente_id);
CREATE INDEX idx_orden_fecha_recepcion ON ordenes (fecha_recepcion DESC);
CREATE INDEX idx_orden_estado         ON ordenes (estado_actual_id);
CREATE INDEX idx_orden_estado_pago    ON ordenes (estado_pago);
CREATE INDEX idx_orden_origen         ON ordenes (origen);
CREATE INDEX idx_orden_codigo_trgm    ON ordenes (codigo_orden varchar_pattern_ops);
CREATE TRIGGER trg_ordenes_upd BEFORE UPDATE ON ordenes
  FOR EACH ROW EXECUTE FUNCTION set_fecha_actualizacion();

-- Un renglón = UN PAR de tenis. Nunca se agrupan pares con detalle de calzado.
CREATE TABLE detalles_orden_servicios (
  detalle_servicio_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_id            INT NOT NULL REFERENCES ordenes(orden_id) ON DELETE CASCADE,
  servicio_id         INT NOT NULL REFERENCES servicios(servicio_id),
  cantidad            INT NOT NULL DEFAULT 1 CHECK (cantidad > 0),
  precio_unitario     NUMERIC(10,2) NOT NULL CHECK (precio_unitario >= 0),
  descuento           NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (descuento >= 0),
  subtotal            NUMERIC(10,2) NOT NULL CHECK (subtotal >= 0),

  -- Identificación del par
  modelo_id           INT NULL REFERENCES modelos_calzado(modelo_id),
  marca               VARCHAR(120) NULL,
  modelo              VARCHAR(120) NULL,
  talla               VARCHAR(20)  NULL,
  color               VARCHAR(60)  NULL,
  descripcion_calzado TEXT NULL,

  -- Ubicación física en almacén
  caja_almacenamiento VARCHAR(40) NULL,
  codigo_ubicacion    VARCHAR(40) NULL,
  notas_especiales    TEXT NULL,

  fecha_creacion      TIMESTAMPTZ NOT NULL DEFAULT now(),
  fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_detalle_servicio_orden ON detalles_orden_servicios (orden_id);
CREATE INDEX idx_detalle_ubicacion ON detalles_orden_servicios (caja_almacenamiento, codigo_ubicacion)
  WHERE codigo_ubicacion IS NOT NULL;
-- Un código de ubicación solo puede estar ocupado por un par a la vez.
-- Al entregar se limpia la ubicación, de modo que el espacio se reutiliza (FUN-09).
CREATE UNIQUE INDEX ux_ubicacion_ocupada ON detalles_orden_servicios (codigo_ubicacion)
  WHERE codigo_ubicacion IS NOT NULL;
CREATE TRIGGER trg_det_serv_upd BEFORE UPDATE ON detalles_orden_servicios
